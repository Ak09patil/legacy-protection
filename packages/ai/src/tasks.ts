/**
 * The two AI tasks. Both return either a validated result or a typed failure;
 * neither can return anything the policy layer hasn't defined.
 */

import { z } from "zod";
import { PlanDocumentSchema, summarisePlan, type ModelOutcome, type PlanDocument, type TextLabel } from "@lp/policy";
import type { LlmProvider } from "./provider.js";
import { extractJsonObject, UNTRUSTED_RULES, wrapUntrusted } from "./untrusted.js";

// ---------------------------------------------------------------------------
// 1. Drafting a plan from the owner's own words
// ---------------------------------------------------------------------------

export type DraftResult =
  | { readonly ok: true; readonly plan: PlanDocument; readonly summary: string[]; readonly model: string }
  | { readonly ok: false; readonly reason: "PROVIDER_UNAVAILABLE" | "INVALID_OUTPUT"; readonly issues: string[] };

const DRAFT_SYSTEM = `You turn a person's description of their wishes into a JSON plan for "Legacy Protection".
${UNTRUSTED_RULES}

Return ONLY one JSON object matching this TypeScript type, with no other keys:
{
  "schemaVersion": 1,
  "trustedContact": { "name": string, "email": string },
  "checkin": { "timeZone": IANA zone, "intervalDays": 1-30, "localHour": 0-23, "localMinute": 0-59 },
  "waitingPeriodHours": integer >= 72,
  "obligations": Array<{
    "id": lowercase-kebab id, "kind": "HOUSEHOLD_EMPLOYEE", "payeeName": string, "payeeEmail": string,
    "description": string, "amountPerPaymentMinor": integer cents, "maxPerMonthMinor": integer cents,
    "currency": "USD", "cadence": "WEEKLY" | "BIWEEKLY" | "MONTHLY", "continueForDaysAfterActivation": 0-120
  }>,
  "onActivation": { "cancelSubscriptions": boolean, "cancelOpenInvoices": boolean, "holdBalanceForEstate": true },
  "contentVisibleTo": Array<"TRUSTED_CONTACT" | "EXECUTOR">
}

Rules:
- Obligations are ONLY ongoing payments to someone who works in the person's home (caregiver, nurse aide, cleaner).
  Never create payments to family, friends, the trusted contact, charities or anyone else.
- The balance always stays for the estate. You cannot send money anywhere else.
- If something is unclear or missing, use safe defaults: weekly check-ins at 10:00, 72-hour waiting period,
  no obligations, both cancellations true, contentVisibleTo empty.`;

export async function draftPlan(provider: LlmProvider, ownerWords: string, timeZoneHint: string): Promise<DraftResult> {
  const wishes = wrapUntrusted("owner_wishes", ownerWords);
  let text: string;
  let model: string;
  try {
    ({ text, model } = await provider.complete({
      system: DRAFT_SYSTEM,
      user: `The person's time zone is ${JSON.stringify(timeZoneHint)}.\nTheir wishes:\n${wishes.block}`,
      maxTokens: 1500,
      json: true,
    }));
  } catch {
    return { ok: false, reason: "PROVIDER_UNAVAILABLE", issues: [] };
  }

  let raw: unknown;
  try {
    raw = extractJsonObject(text);
  } catch {
    return { ok: false, reason: "INVALID_OUTPUT", issues: ["not JSON"] };
  }
  const parsed = PlanDocumentSchema.safeParse(raw);
  if (!parsed.success) {
    return {
      ok: false,
      reason: "INVALID_OUTPUT",
      issues: parsed.error.issues.map((i) => `${i.path.join(".") || "(root)"}: ${i.message}`),
    };
  }
  // The owner reads a summary generated by code from the validated plan, not model prose.
  return { ok: true, plan: parsed.data, summary: summarisePlan(parsed.data), model };
}

// ---------------------------------------------------------------------------
// 2. Labelling risky text on a payment (memo, invoice note, payee name)
// ---------------------------------------------------------------------------

const TEXT_LABELS = [
  "GIFT_CARD_REQUEST",
  "CRYPTO_REQUEST",
  "URGENCY",
  "IMPERSONATION_GOVERNMENT",
  "IMPERSONATION_TECH_SUPPORT",
  "IMPERSONATION_FAMILY",
] as const satisfies readonly TextLabel[];

const LabelOutputSchema = z.object({ labels: z.array(z.enum(TEXT_LABELS)).max(TEXT_LABELS.length) }).strict();

const CLASSIFY_SYSTEM = `You label payment text for signs of scams that target older adults.
${UNTRUSTED_RULES}

Return ONLY {"labels": [...]} using zero or more of exactly these labels:
GIFT_CARD_REQUEST, CRYPTO_REQUEST, URGENCY, IMPERSONATION_GOVERNMENT, IMPERSONATION_TECH_SUPPORT, IMPERSONATION_FAMILY.
Return {"labels": []} if none apply. No other keys, no explanations.`;

export type LabelResult =
  | { readonly ok: true; readonly labels: readonly TextLabel[]; readonly model: string }
  | { readonly ok: false; readonly reason: "PROVIDER_UNAVAILABLE" | "INVALID_OUTPUT" };

export async function labelPaymentText(provider: LlmProvider, text: string): Promise<LabelResult> {
  if (!text.trim()) return { ok: true, labels: [], model: "none" };
  const w = wrapUntrusted("payment_text", text);
  let reply: string;
  let model: string;
  try {
    ({ text: reply, model } = await provider.complete({
      system: CLASSIFY_SYSTEM,
      user: w.block,
      maxTokens: 100,
      json: true,
    }));
  } catch {
    return { ok: false, reason: "PROVIDER_UNAVAILABLE" };
  }
  try {
    const parsed = LabelOutputSchema.safeParse(extractJsonObject(reply));
    if (!parsed.success) return { ok: false, reason: "INVALID_OUTPUT" };
    return { ok: true, labels: [...new Set(parsed.data.labels)], model };
  } catch {
    return { ok: false, reason: "INVALID_OUTPUT" };
  }
}

/**
 * Bridges a labelling failure into the policy engine's outcome type, so a
 * failed or manipulated classifier holds the payment. INV-10
 */
export function labelFailureOutcome(r: Extract<LabelResult, { ok: false }>): ModelOutcome {
  return { status: "UNAVAILABLE", detail: `text labelling ${r.reason.toLowerCase()}` };
}
