/**
 * The plan document: what the owner confirms, and the only source of
 * authority for an activated plan (INV-02).
 *
 * The schema is deliberately narrow. There is no field that could send the
 * balance or an arbitrary payment anywhere (INV-04). Continued payments exist
 * only as capped obligations to payees the owner registered by name.
 */

import { z } from "zod";

const email = z.string().trim().toLowerCase().email().max(254);
const minor = z.number().int().positive().max(10_000_000); // up to $100,000.00
const currency = z.string().regex(/^[A-Z]{3}$/);

export const TrustedContactSchema = z
  .object({
    name: z.string().trim().min(1).max(100),
    email,
  })
  .strict();

export const ObligationSchema = z
  .object({
    id: z.string().regex(/^[a-z0-9-]{1,40}$/),
    kind: z.literal("HOUSEHOLD_EMPLOYEE"),
    payeeName: z.string().trim().min(1).max(100),
    payeeEmail: email,
    description: z.string().trim().max(200),
    amountPerPaymentMinor: minor,
    maxPerMonthMinor: minor,
    currency,
    cadence: z.enum(["WEEKLY", "BIWEEKLY", "MONTHLY"]),
    /** How long payments may continue after activation, so the household can arrange care. */
    continueForDaysAfterActivation: z.number().int().min(0).max(120),
  })
  .strict()
  .refine((o) => o.amountPerPaymentMinor <= o.maxPerMonthMinor, {
    message: "Per-payment amount cannot exceed the monthly cap",
  });

export const PlanDocumentSchema = z
  .object({
    schemaVersion: z.literal(1),
    trustedContact: TrustedContactSchema,
    checkin: z
      .object({
        timeZone: z.string().min(1).max(64),
        intervalDays: z.number().int().min(1).max(30),
        localHour: z.number().int().min(0).max(23),
        localMinute: z.number().int().min(0).max(59),
      })
      .strict(),
    waitingPeriodHours: z.number().int().min(72).max(24 * 30),
    obligations: z.array(ObligationSchema).max(5),
    onActivation: z
      .object({
        cancelSubscriptions: z.boolean(),
        cancelOpenInvoices: z.boolean(),
        /** Always true: the balance waits for the estate. Not configurable. INV-04 */
        holdBalanceForEstate: z.literal(true),
      })
      .strict(),
    /** Roles allowed to see memo and message content (INV-17). Empty by default. */
    contentVisibleTo: z.array(z.enum(["TRUSTED_CONTACT", "EXECUTOR"])).max(2),
  })
  .strict()
  .refine((p) => p.obligations.every((o) => o.payeeEmail !== p.trustedContact.email), {
    message: "The trusted contact cannot also be a payee of the plan (INV-08)",
    path: ["obligations"],
  })
  .refine((p) => new Set(p.obligations.map((o) => o.id)).size === p.obligations.length, {
    message: "Obligation ids must be unique",
    path: ["obligations"],
  });

export type PlanDocument = z.infer<typeof PlanDocumentSchema>;
export type Obligation = z.infer<typeof ObligationSchema>;

function money(minorUnits: number, cur: string): string {
  return new Intl.NumberFormat("en-US", { style: "currency", currency: cur }).format(minorUnits / 100);
}

function every(days: number): string {
  if (days === 1) return "every day";
  if (days === 7) return "every week";
  if (days === 14) return "every 2 weeks";
  if (days % 7 === 0) return `every ${days / 7} weeks`;
  return `every ${days} days`;
}

function duration(hours: number): string {
  if (hours % 168 === 0) return hours === 168 ? "1 week" : `${hours / 168} weeks`;
  if (hours % 24 === 0) return `${hours / 24} days`;
  return `${hours} hours`;
}

function clock(h: number, m: number, timeZone: string): string {
  const t = `${h % 12 === 0 ? 12 : h % 12}:${String(m).padStart(2, "0")} ${h < 12 ? "AM" : "PM"}`;
  let zone = timeZone;
  try {
    zone =
      new Intl.DateTimeFormat("en-US", { timeZone, timeZoneName: "longGeneric" })
        .formatToParts(new Date(0))
        .find((x) => x.type === "timeZoneName")?.value ?? timeZone;
  } catch {
    /* unknown zone: show the IANA name as given */
  }
  return `${t} ${zone}`;
}

const CADENCE = { WEEKLY: "every week", BIWEEKLY: "every 2 weeks", MONTHLY: "every month" } as const;

/**
 * Plain-language summary of exactly what the plan will do, generated by code
 * from the validated document, never by a model. This is what the owner reads
 * and confirms.
 */
export function summarisePlan(p: PlanDocument): string[] {
  const lines: string[] = [];
  lines.push(
    `We'll check in with you ${every(p.checkin.intervalDays)} at ${clock(p.checkin.localHour, p.checkin.localMinute, p.checkin.timeZone)}.`,
  );
  lines.push(
    `Your trusted contact is ${p.trustedContact.name} (${p.trustedContact.email}). They can confirm something has happened to you, but they can't change your plan, release payments or receive money from it.`,
  );
  lines.push(
    `Nothing happens unless you miss your check-ins, ${p.trustedContact.name} confirms, and then another ${duration(p.waitingPeriodHours)} pass with no word from you. Any sign of you cancels it.`,
  );
  if (p.onActivation.cancelSubscriptions) lines.push("If your plan starts, we'll stop your recurring subscriptions.");
  if (p.onActivation.cancelOpenInvoices) lines.push("If your plan starts, we'll cancel invoices you've sent that haven't been paid.");
  for (const o of p.obligations) {
    lines.push(
      `We'll keep paying ${o.payeeName} (${o.description}) ${money(o.amountPerPaymentMinor, o.currency)} ${CADENCE[o.cadence]}, ` +
        `never more than ${money(o.maxPerMonthMinor, o.currency)} a month, for up to ${o.continueForDaysAfterActivation} days.`,
    );
  }
  lines.push("Your remaining balance stays safe in your account for your estate. It is never sent to anyone by this plan.");
  lines.push(
    p.contentVisibleTo.length === 0
      ? "Nobody else can read your payment notes or messages."
      : `Payment notes can be read by: ${p.contentVisibleTo.map((r) => r.toLowerCase().replace("_", " ")).join(" and ")}.`,
  );
  return lines;
}
